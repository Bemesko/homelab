#!/usr/bin/env bash
# Vendors the Grafana community dashboards, with a pinned version and sha256.
#
#   scripts/vendor-dashboards.sh            downloads, checks the upstream sha256, applies
#                                           the patches and writes the JSONs
#   scripts/vendor-dashboards.sh --update   same, but rewrites the lock hashes
#                                           (use it when bumping a dashboard version)
#   scripts/vendor-dashboards.sh --check    offline: checks what is versioned
#
# Lock: kubernetes/workloads/observability/base/dashboards/dashboards.lock
#   name  grafana-folder  url  upstream-sha256  output-sha256
# Patches: .../dashboards/patches/<name>.jq (jq, applied after the common filter).
# Own dashboards (outside the lock) live in <folder>/<name>.json, written by hand.
# The directory's kustomization.yaml (one ConfigMap per dashboard, with the Grafana
# folder in the grafana_folder annotation) is generated here.
# Licenses: the Grafana mixins (Loki, Tempo) are AGPL-3.0; the rest comes from the
# authors cited in the lock (grafana.com) and from the ArgoCD repository (Apache-2.0).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DIR="${ROOT}/kubernetes/workloads/observability/base/dashboards"
LOCK="${DIR}/dashboards.lock"
MODE="${1:-vendor}"
MAX_BYTES=$((900 * 1024))

# Common filter: no __inputs/__requires, null id, stable uid, datasources by uid
# (the DS_* variables of the grafana.com exports are removed).
read -r -d '' COMMON <<'JQ' || true
def ds: if . == "${DS_LOKI}" then "loki" else "prometheus" end;
def isds: type == "string" and test("^\\$\\{DS_[A-Z_]+\\}$");
del(.__inputs, .__requires)
| .id = null
| .uid = $uid
| .tags = ((.tags // []) + ["community"] | unique)
| .templating.list |= map(select((.name | startswith("DS_")) | not))
| walk(
    if type == "object" and (.datasource? | isds)
    then .datasource = {type: (.datasource | ds), uid: (.datasource | ds)}
    elif type == "object" and (.uid? | isds)
    then if .type == "__expr__" then .uid = "__expr__" else .uid = (.uid | ds) end
    else . end)
JQ

transform() { # name raw-file
  local name="$1" raw="$2" patch="${DIR}/patches/${1}.jq"
  local out
  out="$(jq -S --arg uid "$name" "$COMMON" "$raw")"
  if [[ -f "$patch" ]]; then
    out="$(jq -S -L "${DIR}/patches" -f "$patch" <<<"$out")"
  fi
  jq -cS . <<<"$out"
}

sha() { sha256sum "$1" | cut -d' ' -f1; }

# kustomization.yaml: one ConfigMap per dashboard (ArgoCD's last-applied and the
# 1 MiB ConfigMap limit do not add up).
kustomization() {
  cat <<'YAML'
# GENERATED by scripts/vendor-dashboards.sh: do not edit.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
generatorOptions:
  disableNameSuffixHash: true
configMapGenerator:
YAML
  local f folder name
  for f in "${DIR}"/*/*.json; do
    [[ "$f" == "${DIR}/patches/"* ]] && continue
    folder="$(basename "$(dirname "$f")")"
    name="$(basename "$f" .json)"
    cat <<YAML
  - name: grafana-dashboard-${name}
    files:
      - ${folder}/${name}.json
    options:
      labels:
        grafana_dashboard: "1"
      annotations:
        grafana_folder: ${folder}
YAML
  done
}

check() {
  local fail=0 uids f
  uids="$(mktemp)"
  trap 'rm -f "$uids"' RETURN
  while read -r name folder _url _up out; do
    [[ -z "$name" || "$name" == \#* ]] && continue
    f="${DIR}/${folder}/${name}.json"
    if [[ ! -f "$f" ]]; then
      echo "missing ${f#"$ROOT"/}"
      fail=1
      continue
    fi
    [[ "$(sha "$f")" == "$out" ]] || {
      echo "sha256 differs from the lock: ${name} (run --update)"
      fail=1
    }
  done <"$LOCK"
  for f in "${DIR}"/*/*.json; do
    [[ "$f" == "${DIR}/patches/"* ]] && continue
    # shellcheck disable=SC2016
    if grep -qF '${DS_' "$f"; then
      echo "$(basename "$f"): leftover \${DS_...}"
      fail=1
    fi
    [[ "$(wc -c <"$f")" -lt "$MAX_BYTES" ]] || {
      echo "$(basename "$f"): larger than 900 KiB"
      fail=1
    }
    jq -r '.uid' "$f" >>"$uids"
  done
  if [[ -n "$(sort "$uids" | uniq -d)" ]]; then
    echo "duplicate uids: $(sort "$uids" | uniq -d)"
    fail=1
  fi
  diff -q <(kustomization) "${DIR}/kustomization.yaml" >/dev/null ||
    {
      echo "kustomization.yaml out of date (run the script)"
      fail=1
    }
  return "$fail"
}

vendor() {
  local update="$1" tmp new_lock name folder url up got
  tmp="$(mktemp -d)"
  new_lock="${tmp}/lock"
  trap 'rm -rf "$tmp"' RETURN
  while IFS= read -r line; do
    if [[ -z "$line" || "$line" == \#* ]]; then
      echo "$line" >>"$new_lock"
      continue
    fi
    read -r name folder url up _out <<<"$line"
    curl -fsSL --retry 3 -o "${tmp}/${name}.raw" "$url"
    got="$(sha "${tmp}/${name}.raw")"
    if [[ "$up" != "-" && "$got" != "$up" && "$update" != "1" ]]; then
      echo "ERROR: ${name}: the upstream changed (expected ${up}, got ${got})" >&2
      return 1
    fi
    mkdir -p "${DIR}/${folder}"
    transform "$name" "${tmp}/${name}.raw" >"${DIR}/${folder}/${name}.json"
    printf '%s %s %s %s %s\n' "$name" "$folder" "$url" "$got" "$(sha "${DIR}/${folder}/${name}.json")" >>"$new_lock"
    echo "ok ${name} (${folder})"
  done <"$LOCK"
  kustomization >"${DIR}/kustomization.yaml"
  if [[ "$update" == "1" ]]; then cp "$new_lock" "$LOCK"; else
    diff -q <(grep -v '^#' "$LOCK") <(grep -v '^#' "$new_lock") >/dev/null ||
      {
        echo "ERROR: output differs from the lock (patch changed? run --update)" >&2
        return 1
      }
    check
  fi
}

case "$MODE" in
  --check) check ;;
  --update) vendor 1 ;;
  vendor) vendor 0 ;;
  *)
    echo "usage: $0 [--update|--check]" >&2
    exit 2
    ;;
esac
